//! The combined report (`--report FILE`): the settings audit, known
//! vulnerabilities, npm packages and secrets on one HTML page.
//!
//! The page is a single file that loads nothing from the network: the styles
//! and the small script behind the copy buttons are inline, and the fonts are
//! the system's. Everything that comes from the scanned machine (paths,
//! package names, advisory text, check details) goes through `escape`.

use crate::checks::{CheckResult, Status};
use crate::report::{self, Report};
use crate::{npm, secrets, vulns};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Everything the report shows.
pub struct FullReport {
    pub audit: Report,
    /// Were online lookups requested (`--online`)?
    pub online: bool,
    pub vulns: vulns::Scan,
    pub npm: npm::Scan,
    /// The OSV query for npm packages: `None` when online lookups were off,
    /// otherwise whether it worked.
    pub npm_lookup: Option<Result<(), String>>,
    pub secrets: secrets::Scan,
    /// Shown as `~` at the start of paths.
    pub home: Option<PathBuf>,
}

/// How much attention a row needs; also its color.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Tone {
    Crit,
    Warn,
    Ok,
    Unknown,
}

impl Tone {
    fn class(self) -> &'static str {
        match self {
            Tone::Crit => "crit",
            Tone::Warn => "warn",
            Tone::Ok => "ok",
            Tone::Unknown => "unk",
        }
    }
}

/// One expandable row. `title`, `sub` and `body` are HTML (already escaped).
struct Row {
    tone: Tone,
    tag: &'static str,
    title: String,
    sub: String,
    body: String,
    open: bool,
}

/// One entry of "Fix these first". Both parts are HTML.
struct Priority {
    action: String,
    why: String,
}

/// How many entries "Fix these first" shows; the rest stay in their sections.
const MAX_PRIORITIES: usize = 6;

impl FullReport {
    /// Did a scan find malware, a known-exploited vulnerability or a secret
    /// in a file tracked in git?
    pub fn found_threat(&self) -> bool {
        self.npm.malware().next().is_some() || self.vulns.exploited() > 0 || self.secrets.tracked().next().is_some()
    }

    /// Did an online lookup fail, so that something may be missing?
    pub fn incomplete(&self) -> bool {
        !self.gaps().is_empty()
    }

    /// Why something may be missing, in words for the page.
    fn gaps(&self) -> Vec<&'static str> {
        let mut gaps = Vec::new();
        if !self.vulns.warnings.is_empty() {
            gaps.push("a vulnerability lookup failed");
        }
        if !self.vulns.skipped.is_empty() {
            gaps.push("a lockfile could not be read");
        }
        if matches!(self.npm_lookup, Some(Err(_))) {
            gaps.push("the OSV lookup for npm packages failed");
        }
        if self.npm.global_dir_problem.is_some() {
            gaps.push("npm's own global directory could not be located");
        }
        if self.secrets.git_unknown().next().is_some() {
            gaps.push("git could not tell whether a file with a secret is tracked");
        }
        gaps
    }

    pub fn to_html(&self) -> String {
        let time = report::short_time(&self.audit.timestamp);
        let priorities = self.priorities();
        let mut out = String::new();
        let _ = write!(
            out,
            "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
             <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
             <meta name=\"color-scheme\" content=\"light dark\">\n\
             <title>SwordCheck report · {}</title>\n<style>{STYLE}</style>\n</head>\n<body>\n<div class=\"wrap\">\n",
            escape(&time)
        );
        self.header(&mut out, &time);
        self.nav(&mut out, priorities.len());
        self.overview(&mut out, &priorities);
        self.audit_section(&mut out);
        self.vulns_section(&mut out);
        self.npm_section(&mut out);
        self.secrets_section(&mut out);
        let _ = write!(
            out,
            "<footer>\n<p>Generated by SwordCheck {} on {}. This file loads nothing from the network.</p>\n\
             <p>Score: a passing check earns its full weight, a warning half, a failure none; \
             checks that could not be evaluated or have an exception are left out.</p>\n</footer>\n\
             </div>\n<script>{SCRIPT}</script>\n</body>\n</html>\n",
            self.audit.version,
            escape(&time)
        );
        out
    }

    fn path(&self, path: &Path) -> String {
        escape(&secrets::display_path(path, self.home.as_deref()))
    }

    /// A `<ul>` of paths, with "and N more" when only some are listed.
    fn paths(&self, paths: &[PathBuf], total: usize) -> String {
        let mut out = String::from("<ul class=\"paths\">");
        for path in paths {
            let _ = write!(out, "<li>{}</li>", self.path(path));
        }
        if total > paths.len() {
            let _ = write!(out, "<li>and {} more</li>", total - paths.len());
        }
        out.push_str("</ul>");
        out
    }

    fn header(&self, out: &mut String, time: &str) {
        let online = if self.online {
            "Online lookups on: package names and versions were sent to OSV.dev, NVD, CISA and FIRST"
        } else {
            "Online lookups off: nothing left this Mac"
        };
        let _ = write!(
            out,
            "<header>\n<span class=\"brand\">SwordCheck report</span>\n<h1>Security check-up of this Mac</h1>\n\
             <div class=\"meta\"><span>{}</span><span>{}</span><span>SwordCheck {}</span></div>\n\
             <div class=\"assure\"><span>Read-only: no setting was changed</span><span>{online}</span>\
             <span>Secret values are masked</span></div>\n</header>\n",
            escape(&self.audit.os_version),
            escape(time),
            self.audit.version
        );
    }

    fn nav(&self, out: &mut String, priorities: usize) {
        let vulns = if self.online {
            let count = self.vulns.findings.len()
                + self
                    .vulns
                    .system
                    .iter()
                    .filter(|item| !item.exploited.is_empty())
                    .count();
            // A failed lookup or an unread lockfile may hide findings: that is
            // never a clean 0.
            match (self.vulns.exploited(), count, self.vulns.incomplete()) {
                (1.., _, _) => (Tone::Crit, count.to_string()),
                (0, 1.., _) => (Tone::Warn, count.to_string()),
                (0, 0, true) => (Tone::Warn, "incomplete".to_string()),
                (0, 0, false) => (Tone::Ok, "0".to_string()),
            }
        } else {
            (Tone::Unknown, "offline".to_string())
        };
        let npm_incomplete = matches!(self.npm_lookup, Some(Err(_))) || self.npm.global_dir_problem.is_some();
        let npm = match (self.npm.malware().count(), self.npm.findings.len(), npm_incomplete) {
            (1.., count, _) => (Tone::Crit, count.to_string()),
            (0, count @ 1.., _) => (Tone::Warn, count.to_string()),
            (0, 0, true) => (Tone::Warn, "incomplete".to_string()),
            (0, 0, false) => (Tone::Ok, "0".to_string()),
        };
        let secrets = self.secrets.unique_secrets();
        let secrets_tone = match (self.secrets.tracked().count(), secrets) {
            (1.., _) => Tone::Crit,
            (0, 1..) => Tone::Warn,
            _ => Tone::Ok,
        };
        let first_tone = if priorities > 0 { Tone::Crit } else { Tone::Ok };
        let links = [
            ("first", "Fix first", first_tone, priorities.to_string()),
            ("audit", "Settings", grade_tone(&self.audit), self.score_text()),
            ("vulns", "Vulnerabilities", vulns.0, vulns.1),
            ("npm", "npm", npm.0, npm.1),
            ("secrets", "Secrets", secrets_tone, secrets.to_string()),
        ];
        out.push_str("<nav class=\"jump\" aria-label=\"Sections\">");
        for (id, label, tone, value) in links {
            let _ = write!(
                out,
                "<a href=\"#{id}\">{label} <b class=\"{}\">{value}</b></a>",
                tone.class()
            );
        }
        out.push_str("</nav>\n");
    }

    /// "74/100", or "n/a" when no check could be evaluated.
    fn score_text(&self) -> String {
        if self.audit.scorable {
            format!("{}/100", self.audit.score)
        } else {
            "n/a".to_string()
        }
    }

    fn overview(&self, out: &mut String, priorities: &[Priority]) {
        out.push_str(
            "<div class=\"overview\" id=\"first\">\n<div class=\"panel score\" aria-label=\"Settings score\">\n",
        );
        let audit = &self.audit;
        if audit.scorable {
            let _ = write!(
                out,
                "<div class=\"score-top\"><span class=\"score-num\">{}<small> / 100</small></span>\
                 <span class=\"grade {}\">Grade {}</span>",
                audit.score,
                grade_tone(audit).class(),
                audit.grade
            );
            if let Some(previous) = &audit.previous {
                let delta = i64::from(audit.score) - i64::from(previous.score);
                let (tone, change) = match delta {
                    0 => (Tone::Unknown, "unchanged".to_string()),
                    1.. => (Tone::Ok, format!("+{delta}")),
                    _ => (Tone::Crit, delta.to_string()),
                };
                let _ = write!(
                    out,
                    "<span class=\"delta {}\">{change} since {}</span>",
                    tone.class(),
                    escape(&report::short_time(&previous.timestamp))
                );
            }
            out.push_str("</div>\n");
            out.push_str(&scale(
                audit.score,
                audit.previous.as_ref().map(|previous| previous.score),
            ));
        } else {
            out.push_str(
                "<div class=\"score-top\"><span class=\"score-num\">n/a</span>\
                 <span class=\"grade unk\">No score</span></div>\n\
                 <p class=\"muted\">No check could be evaluated, so there is nothing to score.</p>\n",
            );
        }
        let summary = &audit.summary;
        let _ = write!(
            out,
            "<div class=\"counts\"><div><b class=\"ok\">{}</b><span>pass</span></div>\
             <div><b class=\"warn\">{}</b><span>warn</span></div><div><b class=\"crit\">{}</b><span>fail</span></div>\
             <div><b class=\"unk\">{}</b><span>unknown</span></div><div><b class=\"unk\">{}</b><span>exempt</span></div></div>\n</div>\n",
            summary.pass, summary.warn, summary.fail, summary.unknown, summary.exempt
        );

        out.push_str("<div class=\"panel todo\">\n<h2>Fix these first</h2>\n");
        // Whether the list is empty or not, say what it may be missing.
        let gaps = self.gaps().join("; ");
        if priorities.is_empty() && !gaps.is_empty() {
            let _ = writeln!(
                out,
                "<p>No urgent finding in what could be checked, but this list may be incomplete: {gaps}. \
                 See the notes below.</p>"
            );
        } else if priorities.is_empty() {
            out.push_str(
                "<p>Nothing urgent: no failing check, malware, known-exploited vulnerability or secret in a git-tracked file.</p>\n",
            );
        } else {
            out.push_str("<p>Ordered by risk across every scan.</p>\n");
            if !gaps.is_empty() {
                let _ = writeln!(
                    out,
                    "<p class=\"note warn\">This list may be incomplete: {gaps}. See the notes below.</p>"
                );
            }
            out.push_str("<ol>\n");
            for priority in priorities.iter().take(MAX_PRIORITIES) {
                let _ = writeln!(
                    out,
                    "<li><div><p>{}</p><p>{}</p></div></li>",
                    priority.action, priority.why
                );
            }
            out.push_str("</ol>\n");
            if priorities.len() > MAX_PRIORITIES {
                let _ = writeln!(
                    out,
                    "<p class=\"muted\">And {} more in the sections below.</p>",
                    priorities.len() - MAX_PRIORITIES
                );
            }
        }
        out.push_str("</div>\n</div>\n");
    }

    /// Malware first, then what is exploited in the wild, then secrets that
    /// may have leaked, then failing settings by weight.
    fn priorities(&self) -> Vec<Priority> {
        let mut list = Vec::new();
        for finding in self.npm.malware() {
            list.push(Priority {
                action: format!("Remove <strong>{}</strong>.", escape(&npm_title(finding))),
                why: "Malicious npm package. Rotate the npm, GitHub and cloud credentials on this Mac.".to_string(),
            });
        }
        // A malicious npm package is usually both installed and pinned in a
        // lockfile; the npm entry above already says to remove it.
        let listed = |finding: &vulns::Finding| {
            finding.ecosystem == "npm"
                && self
                    .npm
                    .malware()
                    .any(|npm| npm.package == finding.package && npm.version == finding.version)
        };
        for finding in self
            .vulns
            .findings
            .iter()
            .filter(|finding| finding.malware && !listed(finding))
        {
            list.push(Priority {
                action: format!(
                    "Remove <strong>{} {}</strong>.",
                    escape(&finding.package),
                    escape(&finding.version)
                ),
                why: format!("Advisory {} marks this version as malware.", escape(&finding.id)),
            });
        }
        for item in self.vulns.system.iter().filter(|item| !item.exploited.is_empty()) {
            list.push(Priority {
                action: format!("Update <strong>{}</strong>.", escape(&item.title())),
                why: format!(
                    "{} is exploited in the wild (CISA KEV).",
                    escape(&item.exploited[0].cve)
                ),
            });
        }
        for finding in self
            .vulns
            .findings
            .iter()
            .filter(|finding| finding.kev.is_some() && !finding.malware)
        {
            let target = match finding.fixed.first() {
                Some(fixed) => format!(" to {}", escape(fixed)),
                None => String::new(),
            };
            list.push(Priority {
                action: format!(
                    "Update <strong>{} {}</strong>{target}.",
                    escape(&finding.package),
                    escape(&finding.version)
                ),
                why: format!(
                    "{} is exploited in the wild (CISA KEV).",
                    escape(finding.cves.first().unwrap_or(&finding.id))
                ),
            });
        }
        let mut seen = Vec::new();
        for finding in self.secrets.tracked() {
            if seen.contains(&finding.secret_id) {
                continue;
            }
            seen.push(finding.secret_id);
            list.push(Priority {
                action: format!(
                    "Revoke <strong>{}</strong> in {}.",
                    escape(finding.name.as_deref().unwrap_or(finding.provider)),
                    escape(&short_file(&finding.path))
                ),
                why: "The file is tracked in git, so treat the secret as leaked.".to_string(),
            });
        }
        let mut failing: Vec<&CheckResult> = self.audit.checks.iter().filter(|check| check.is_failure()).collect();
        failing.sort_by_key(|check| std::cmp::Reverse(check.weight));
        for check in failing {
            list.push(Priority {
                action: format!("<strong>{}</strong>", escape(check.name)),
                why: escape(if check.advice.is_empty() {
                    check.detail.as_str()
                } else {
                    check.advice
                }),
            });
        }
        list
    }

    fn audit_section(&self, out: &mut String) {
        section_head(out, "audit", "Settings audit", "", true);
        // Issues first (failures before warnings, heavier first), then what
        // could not be checked, then exceptions; passing checks are folded.
        let rank = |check: &CheckResult| match (&check.exempt, check.status) {
            (None, Status::Fail) => 0,
            (None, Status::Warn) => 1,
            (None, Status::Unknown) => 2,
            (Some(_), _) => 3,
            (None, Status::Pass) => 4,
        };
        let mut checks: Vec<&CheckResult> = self.audit.checks.iter().collect();
        checks.sort_by_key(|check| (rank(check), std::cmp::Reverse(check.weight)));
        let (passed, shown): (Vec<&CheckResult>, Vec<&CheckResult>) =
            checks.into_iter().partition(|check| rank(check) == 4);

        out.push_str("<div class=\"list\">\n");
        for check in shown {
            write_row(out, &check_row(check));
        }
        if !passed.is_empty() {
            let names: Vec<&str> = passed.iter().map(|check| check.name).collect();
            let _ = writeln!(
                out,
                "<details class=\"more\"><summary>{} passed: {}</summary>",
                plural(passed.len(), "check", "checks"),
                escape(&names.join(", "))
            );
            for check in passed {
                write_row(out, &check_row(check));
            }
            out.push_str("</details>\n");
        }
        out.push_str("</div>\n</section>\n");
    }

    fn vulns_section(&self, out: &mut String) {
        let scan = &self.vulns;
        let counts = format!(
            "{} · {} · {}",
            plural(scan.lockfiles, "lockfile", "lockfiles"),
            plural(scan.packages, "package", "packages"),
            plural(scan.system.len(), "app or formula", "apps and formulae")
        );
        section_head(out, "vulns", "Known vulnerabilities", &counts, false);
        if !self.online {
            note(
                out,
                Tone::Unknown,
                "Online lookups were off, so no version was looked up: this is an inventory only. \
                 Run with --online to check them.",
            );
        }
        if let Some(skipped) = scan.skipped_note(self.home.as_deref()) {
            note(out, Tone::Warn, &skipped);
        }
        for warning in &scan.warnings {
            note(out, Tone::Warn, warning);
        }
        if let Some(unmatched) = scan.unmatched_note() {
            note(out, Tone::Unknown, &unmatched);
        }

        let mut rows = Vec::new();
        for item in scan.system.iter().filter(|item| !item.exploited.is_empty()) {
            let mut body = String::from("<dl class=\"facts\">");
            for vuln in &item.exploited {
                let ransomware = if vuln.ransomware { ", used in ransomware" } else { "" };
                let _ = write!(
                    body,
                    "<dt>{}</dt><dd>{}, in CISA KEV since {}{ransomware}</dd>",
                    escape(&vuln.cve),
                    escape(&vuln.name),
                    escape(&vuln.date_added)
                );
            }
            let _ = write!(
                body,
                "<dt>Product</dt><dd class=\"mono\">{}</dd></dl><p class=\"advice\">Update it.</p>",
                escape(&item.cpe)
            );
            let more = match item.exploited.len() {
                1 => String::new(),
                count => format!(" and {} more", count - 1),
            };
            rows.push(Row {
                tone: Tone::Crit,
                tag: "KEV",
                title: escape(&item.title()),
                sub: format!(
                    "{} · {}{more}",
                    escape(&item.exploited[0].cve),
                    escape(&item.exploited[0].name)
                ),
                body,
                open: true,
            });
        }
        for finding in &scan.findings {
            rows.push(self.finding_row(finding));
        }
        for item in scan.system.iter().filter(|item| item.error.is_some()) {
            rows.push(Row {
                tone: Tone::Warn,
                tag: "Not checked",
                title: escape(&item.title()),
                sub: format!(
                    "The NVD lookup failed: {}",
                    escape(item.error.as_deref().unwrap_or_default())
                ),
                body: format!(
                    "<dl class=\"facts\"><dt>Product</dt><dd class=\"mono\">{}</dd></dl>\
                     <p>Run the scan again later to check it.</p>",
                    escape(&item.cpe)
                ),
                open: false,
            });
        }

        out.push_str("<div class=\"list\">\n");
        if rows.is_empty() {
            let empty = match (self.online, scan.incomplete()) {
                (false, _) => "Nothing was looked up.",
                (true, false) => "No known vulnerability affects the scanned versions.",
                (true, true) => {
                    "Nothing found in what could be checked; what the notes above say was not checked may hide findings."
                }
            };
            let _ = writeln!(out, "<p class=\"empty\">{empty}</p>");
        }
        for row in &rows {
            write_row(out, row);
        }
        let quiet: Vec<String> = scan
            .system
            .iter()
            .filter(|item| item.exploited.is_empty() && item.error.is_none())
            .map(|item| item.title())
            .collect();
        if !quiet.is_empty() {
            let label = if self.online {
                "with no known-exploited vulnerability"
            } else {
                "found, not looked up"
            };
            let _ = writeln!(
                out,
                "<details class=\"more\"><summary>{} {label}</summary>\
                 <p class=\"more-list\">{}</p></details>",
                plural(quiet.len(), "app or formula", "apps and formulae"),
                escape(&quiet.join(", "))
            );
        }
        out.push_str("</div>\n</section>\n");
    }

    fn finding_row(&self, finding: &vulns::Finding) -> Row {
        let (tag, tone) = match (finding.malware, &finding.kev, finding.severity) {
            (true, _, _) => ("Malware", Tone::Crit),
            (_, Some(_), _) => ("KEV", Tone::Crit),
            (_, _, vulns::Severity::Critical) => ("Critical", Tone::Crit),
            (_, _, vulns::Severity::High) => ("High", Tone::Warn),
            (_, _, vulns::Severity::Medium) => ("Medium", Tone::Unknown),
            (_, _, vulns::Severity::Low) => ("Low", Tone::Unknown),
            (_, _, vulns::Severity::Unknown) => ("Unrated", Tone::Unknown),
        };
        let mut advisory = escape(&finding.id);
        if !finding.cves.is_empty() {
            let _ = write!(advisory, " · {}", escape(&finding.cves.join(", ")));
        }
        let mut body = format!("<dl class=\"facts\"><dt>Advisory</dt><dd class=\"mono\">{advisory}</dd>");
        if let Some(kev) = &finding.kev {
            let ransomware = if kev.ransomware { ", used in ransomware" } else { "" };
            let _ = write!(
                body,
                "<dt>Exploited</dt><dd>In CISA KEV since {}{ransomware}</dd>",
                escape(&kev.date_added)
            );
        }
        if let Some(epss) = finding.epss {
            let _ = write!(
                body,
                "<dt>EPSS</dt><dd>{:.1}% chance of exploitation in 30 days</dd>",
                epss * 100.0
            );
        }
        if !finding.fixed.is_empty() {
            let _ = write!(body, "<dt>Fixed in</dt><dd>{}</dd>", escape(&finding.fixed.join(", ")));
        }
        let _ = write!(
            body,
            "</dl><p>Pinned by {}</p>{}",
            plural(finding.lockfile_count, "lockfile", "lockfiles"),
            self.paths(&finding.lockfiles, finding.lockfile_count)
        );
        Row {
            tone,
            tag,
            title: format!("{} {}", escape(&finding.package), escape(&finding.version)),
            sub: format!("{} · {}", escape(finding.ecosystem), escape(&finding.summary)),
            body,
            open: tone == Tone::Crit,
        }
    }

    fn npm_section(&self, out: &mut String) {
        let scan = &self.npm;
        let source = match &self.npm_lookup {
            Some(Ok(())) => "built-in list + OSV.dev",
            Some(Err(_)) => "built-in list + OSV.dev (incomplete)",
            None => "built-in list only (online lookups off)",
        };
        let counts = format!(
            "{} · {} · {source}",
            plural(scan.roots.len(), "directory", "directories"),
            plural(scan.packages, "install", "installs")
        );
        section_head(out, "npm", "npm packages", &counts, false);
        if let Some(Err(err)) = &self.npm_lookup {
            note(
                out,
                Tone::Warn,
                &format!(
                    "The OSV lookup failed, so the packages it did not answer for were checked against the built-in list only: {err}"
                ),
            );
        }
        if let Some(text) = scan.global_dir_note() {
            note(out, Tone::Warn, &text);
        }
        out.push_str("<div class=\"list\">\n");
        match (scan.findings.is_empty(), &self.npm_lookup, &scan.global_dir_problem) {
            (true, Some(Err(_)), _) => out.push_str(
                "<p class=\"empty\">No malicious or suspicious package in the built-in list; \
                 packages known only to OSV.dev were not checked.</p>\n",
            ),
            (true, _, Some(_)) => out.push_str(
                "<p class=\"empty\">No malicious or suspicious package in the directories that were scanned.</p>\n",
            ),
            (true, _, None) => out.push_str("<p class=\"empty\">No malicious or suspicious package found.</p>\n"),
            (false, _, _) => {}
        }
        for finding in scan.malware().chain(scan.suspicious()) {
            let malware = finding.kind.is_malware();
            let tag = match finding.kind {
                _ if malware => "Malware",
                npm::Kind::Unread => "Unread",
                _ => "Script",
            };
            let body = format!(
                "<p>{} · found in {}</p>{}<p class=\"advice\">{}</p>",
                finding.kind.label().to_lowercase(),
                plural(finding.count, "install", "installs"),
                self.paths(&finding.paths, finding.count),
                finding.kind.advice()
            );
            write_row(
                out,
                &Row {
                    tone: if malware { Tone::Crit } else { Tone::Warn },
                    tag,
                    title: escape(&npm_title(finding)),
                    sub: escape(&finding.reason),
                    body,
                    open: malware,
                },
            );
        }
        out.push_str("</div>\n</section>\n");
    }

    fn secrets_section(&self, out: &mut String) {
        let scan = &self.secrets;
        let counts = format!(
            "{} · {} · {}",
            plural(scan.files_scanned, "file", "files"),
            plural(scan.unique_secrets(), "secret", "secrets"),
            plural(scan.findings.len(), "place", "places")
        );
        section_head(out, "secrets", "Secrets on disk", &counts, false);
        let unknown = scan.git_unknown().count();
        if unknown > 0 {
            note(
                out,
                Tone::Warn,
                &format!(
                    "Git could not tell whether {} tracked, so a leaked secret may be missing from \"Fix these first\".",
                    plural(unknown, "location is", "locations are")
                ),
            );
        }
        if scan.files_skipped > 0 {
            note(
                out,
                Tone::Unknown,
                &format!(
                    "{} skipped, not scanned: {}",
                    plural(scan.files_skipped, "file was", "files were"),
                    scan.skipped.reasons()
                ),
            );
        }
        if let Some(folders) = scan.skipped.folders_note() {
            note(out, Tone::Unknown, &folders);
        }
        out.push_str("<div class=\"list\">\n");
        if scan.findings.is_empty() {
            out.push_str("<p class=\"empty\">No secrets found.</p>\n");
        }
        let mut findings: Vec<&secrets::Finding> = scan.findings.iter().collect();
        findings.sort_by_key(|finding| (!finding.git_tracked, !finding.others_can_read));
        for finding in findings {
            write_row(out, &self.secret_row(finding));
        }
        out.push_str("</div>\n</section>\n");
    }

    fn secret_row(&self, finding: &secrets::Finding) -> Row {
        let tone = match (finding.git_tracked, finding.others_can_read || finding.git_unknown) {
            (true, _) => Tone::Crit,
            (_, true) => Tone::Warn,
            _ => Tone::Unknown,
        };
        let what = finding.name.as_deref().unwrap_or(finding.provider);
        let mut body = format!(
            "<dl class=\"facts\"><dt>Where</dt><dd class=\"mono\">{}:{}</dd>",
            self.path(&finding.path),
            finding.line
        );
        if finding.occurrences > 1 {
            let _ = write!(
                body,
                "<dt>Repeated</dt><dd>{} times in this file</dd>",
                finding.occurrences
            );
        }
        if let Some(mode) = &finding.mode {
            let readable = if finding.others_can_read {
                ", readable by other users"
            } else {
                ""
            };
            let _ = write!(body, "<dt>File mode</dt><dd>{}{readable}</dd>", escape(mode));
        }
        let copies: Vec<&secrets::Finding> = self
            .secrets
            .findings
            .iter()
            .filter(|other| other.secret_id == finding.secret_id && other.path != finding.path)
            .collect();
        for copy in &copies {
            let _ = write!(
                body,
                "<dt>Also in</dt><dd class=\"mono\">{}</dd>",
                self.path(&copy.path)
            );
        }
        body.push_str("</dl>");
        if finding.git_tracked {
            body.push_str(
                "<p class=\"advice\">This file is tracked in git. If the repository was ever shared, treat the \
                 secret as leaked: revoke and rotate it, then untrack the file.</p>",
            );
        } else if finding.git_unknown {
            let _ = write!(body, "<p class=\"advice\">{}</p>", escape(secrets::GIT_UNKNOWN_ADVICE));
        }
        if finding.others_can_read && !finding.git_tracked {
            body.push_str(&command(&format!(
                "chmod 600 {}",
                shell_quote(&secrets::display_path(&finding.path, self.home.as_deref()))
            )));
        }
        Row {
            tone,
            tag: tag_for(finding.provider),
            title: format!("{} in {}", escape(what), escape(&short_file(&finding.path))),
            sub: format!("<span class=\"mono\">{}</span>", escape(&finding.masked)),
            body,
            open: tone == Tone::Crit,
        }
    }
}

/// "1 file", "3 files".
fn plural(count: usize, one: &str, many: &str) -> String {
    format!("{count} {}", if count == 1 { one } else { many })
}

/// A one-word tag from a provider name ("AWS access key" → "AWS").
fn tag_for(provider: &'static str) -> &'static str {
    provider.split(' ').next().unwrap_or(provider)
}

fn npm_title(finding: &npm::Finding) -> String {
    let version = if finding.version.is_empty() {
        "?"
    } else {
        &finding.version
    };
    format!("{}@{version}", finding.package)
}

/// `project/.env` says more than `.env` when many projects have one.
fn short_file(path: &Path) -> String {
    let mut parts: Vec<String> = path
        .iter()
        .rev()
        .take(2)
        .map(|part| part.to_string_lossy().into_owned())
        .collect();
    parts.reverse();
    parts.join("/")
}

/// Quotes a path for the shell unless it is plain. `~/` stays unquoted so
/// that the shell still expands it.
fn shell_quote(path: &str) -> String {
    let (home, rest) = match path.strip_prefix("~/") {
        Some(rest) => ("~/", rest),
        None => ("", path),
    };
    let plain = rest.chars().all(|c| c.is_ascii_alphanumeric() || "/._-+".contains(c));
    if plain {
        format!("{home}{rest}")
    } else {
        format!("{home}'{}'", rest.replace('\'', r"'\''"))
    }
}

fn grade_tone(audit: &Report) -> Tone {
    match (audit.scorable, audit.grade) {
        (false, _) => Tone::Unknown,
        (true, "A" | "B") => Tone::Ok,
        (true, "C") => Tone::Warn,
        _ => Tone::Crit,
    }
}

/// The 0–100 scale with the grade bands, the score and the previous score.
/// One point is 4 units wide.
fn scale(score: u32, previous: Option<u32>) -> String {
    let x = |value: u32| value.min(100) * 4;
    let mut svg = String::from(
        "<div class=\"scale\" aria-hidden=\"true\"><svg viewBox=\"0 0 400 46\">\
         <rect x=\"0\" y=\"12\" width=\"160\" height=\"10\" class=\"band f\"/>\
         <rect x=\"160\" y=\"12\" width=\"80\" height=\"10\" class=\"band d\"/>\
         <rect x=\"240\" y=\"12\" width=\"60\" height=\"10\" class=\"band c\"/>\
         <rect x=\"300\" y=\"12\" width=\"60\" height=\"10\" class=\"band b\"/>\
         <rect x=\"360\" y=\"12\" width=\"40\" height=\"10\" class=\"band a\"/>\
         <text x=\"80\" y=\"40\" text-anchor=\"middle\">F</text>\
         <text x=\"200\" y=\"40\" text-anchor=\"middle\">D</text>\
         <text x=\"270\" y=\"40\" text-anchor=\"middle\">C</text>\
         <text x=\"330\" y=\"40\" text-anchor=\"middle\">B</text>\
         <text x=\"380\" y=\"40\" text-anchor=\"middle\">A</text>",
    );
    if let Some(previous) = previous {
        let at = x(previous);
        let anchor = if previous < 50 { "start" } else { "end" };
        let _ = write!(
            svg,
            "<rect x=\"{}\" y=\"9\" width=\"2\" height=\"16\" class=\"previous\"/>\
             <text x=\"{at}\" y=\"7\" text-anchor=\"{anchor}\">{previous} before</text>",
            at.saturating_sub(1)
        );
    }
    let _ = writeln!(
        svg,
        "<rect x=\"{}\" y=\"4\" width=\"4\" height=\"26\" rx=\"2\" class=\"marker\"/></svg></div>",
        x(score).saturating_sub(2).min(396)
    );
    svg
}

fn section_head(out: &mut String, id: &str, title: &str, counts: &str, expand: bool) {
    let _ = write!(
        out,
        "<section id=\"{id}\">\n<div class=\"sec-head\">\n<h2>{title}</h2>\n"
    );
    if !counts.is_empty() {
        let _ = writeln!(out, "<p>{counts}</p>");
    }
    if expand {
        let _ = writeln!(
            out,
            "<div class=\"tools\"><button type=\"button\" data-toggle=\"{id}\">Expand all</button></div>"
        );
    }
    out.push_str("</div>\n");
}

fn note(out: &mut String, tone: Tone, text: &str) {
    let _ = writeln!(out, "<p class=\"note {}\">{}</p>", tone.class(), escape(text));
}

/// A command to run, with a copy button.
fn command(text: &str) -> String {
    format!(
        "<div class=\"cmd\"><pre>{}</pre><button type=\"button\" data-copy>Copy</button></div>",
        escape(text)
    )
}

fn check_row(check: &CheckResult) -> Row {
    let (tone, tag) = match (&check.exempt, check.status) {
        (Some(_), _) => (Tone::Unknown, "Exempt"),
        (None, Status::Fail) => (Tone::Crit, "Fail"),
        (None, Status::Warn) => (Tone::Warn, "Warn"),
        (None, Status::Unknown) => (Tone::Unknown, "Unknown"),
        (None, Status::Pass) => (Tone::Ok, "Pass"),
    };
    let counted = if check.exempt.is_some() { ", not counted" } else { "" };
    let mut body = format!(
        "<dl class=\"facts\"><dt>Weight</dt><dd>{} · {}{counted}</dd>",
        check.weight,
        check.severity.label()
    );
    if let Some(cis) = check.cis {
        let _ = write!(body, "<dt>CIS</dt><dd>{cis}</dd>");
    }
    body.push_str("</dl>");
    if let Some(reason) = &check.exempt {
        let _ = write!(
            body,
            "<p>Exception: {}. It does not count toward the score.</p>",
            escape(reason)
        );
    }
    if check.is_issue() {
        if !check.advice.is_empty() {
            let _ = write!(body, "<p class=\"advice\">{}</p>", escape(check.advice));
        }
        if let Some(fix) = &check.fix {
            body.push_str(&command(&fix.command_line()));
        }
    }
    Row {
        tone,
        tag,
        title: escape(check.name),
        sub: escape(&check.detail),
        body,
        open: false,
    }
}

fn write_row(out: &mut String, row: &Row) {
    let _ = writeln!(
        out,
        "<details class=\"item {}\"{}><summary><span class=\"stripe\"></span><span class=\"tag\">{}</span>\
         <span class=\"title\"><strong>{}</strong><span>{}</span></span><span class=\"chev\">▶</span></summary>\
         <div class=\"body\">{}</div></details>",
        row.tone.class(),
        if row.open { " open" } else { "" },
        row.tag,
        row.title,
        row.sub,
        row.body
    );
}

/// Makes text safe inside HTML elements and quoted attributes.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

